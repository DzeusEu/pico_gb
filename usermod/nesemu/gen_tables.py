MODES = ["IMP","ACC","IMM","ZP","ZPX","ZPY","ABS","ABX","ABY","IZX","IZY","IND","REL"]
ins = [("NOP", "IMP", 2, 0)] * 256     # (mnemonic, mode, cycles, page-cross penalty)
ins = list(ins)
def setop(op, m, mode, cyc, pg=0):
    ins[op] = (m, mode, cyc, pg)

# cc = 01 ALU
alu = ["ORA","AND","EOR","ADC","STA","LDA","CMP","SBC"]
m01 = ["IZX","ZP","IMM","ABS","IZY","ZPX","ABY","ABX"]
c01 = [6, 3, 2, 4, 5, 4, 4, 4]
for a, name in enumerate(alu):
    for b, mode in enumerate(m01):
        op = a << 5 | b << 2 | 1
        if name == "STA":
            if mode == "IMM":
                continue                      # 0x89 = NOP imm (below)
            cyc = {"IZX":6,"ZP":3,"ABS":4,"IZY":6,"ZPX":4,"ABY":5,"ABX":5}[mode]
            setop(op, name, mode, cyc, 0)
        else:
            pg = 1 if mode in ("IZY","ABY","ABX") else 0
            setop(op, name, mode, c01[b] + (1 if mode == "IZY" and False else 0), pg)
# fix izy base cycles: 5 (+1 on crossing)
# cc = 10 shifts / inc dec / ldx stx
sh = ["ASL","ROL","LSR","ROR","STX","LDX","DEC","INC"]
for a, name in enumerate(sh):
    base = a << 5 | 2
    if name in ("ASL","ROL","LSR","ROR","DEC","INC"):
        modes = {1:("ZP",5), 3:("ABS",6), 5:("ZPX",6), 7:("ABX",7)}
        for b, (mode, cyc) in modes.items():
            setop(base | b << 2, name, mode, cyc, 0)
        if name in ("ASL","ROL","LSR","ROR"):
            setop(base | 2 << 2, name, "ACC", 2, 0)
    elif name == "STX":
        setop(base | 1 << 2, "STX", "ZP", 3); setop(base | 3 << 2, "STX", "ABS", 4); setop(base | 5 << 2, "STX", "ZPY", 4)
    else:
        setop(base | 0 << 2, "LDX", "IMM", 2); setop(base | 1 << 2, "LDX", "ZP", 3); setop(base | 3 << 2, "LDX", "ABS", 4)
        setop(base | 5 << 2, "LDX", "ZPY", 4); setop(base | 7 << 2, "LDX", "ABY", 4, 1)
setop(0x8A,"TXA","IMP",2); setop(0xAA,"TAX","IMP",2); setop(0xCA,"DEX","IMP",2); setop(0xEA,"NOP","IMP",2)
setop(0x9A,"TXS","IMP",2); setop(0xBA,"TSX","IMP",2)
# cc = 00
setop(0x24,"BIT","ZP",3); setop(0x2C,"BIT","ABS",4)
