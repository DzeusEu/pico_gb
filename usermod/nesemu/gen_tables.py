        if name == "SAX":
            t = {0:("IZX",6),1:("ZP",3),3:("ABS",4),5:("ZPY",4)}
            if b in t: setop(op, name, t[b][0], t[b][1])
        elif name == "LAX":
            t = {0:("IZX",6,0),1:("ZP",3,0),3:("ABS",4,0),4:("IZY",5,1),5:("ZPY",4,0),7:("ABY",4,1)}
