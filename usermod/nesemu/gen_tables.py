setop(0xE0,"CPX","IMM",2); setop(0xE4,"CPX","ZP",3); setop(0xEC,"CPX","ABS",4)
for op, n in ((0x10,"BPL"),(0x30,"BMI"),(0x50,"BVC"),(0x70,"BVS"),(0x90,"BCC"),(0xB0,"BCS"),(0xD0,"BNE"),(0xF0,"BEQ")):
    setop(op, n, "REL", 2)
for op, n, c in ((0x00,"BRK",7),(0x40,"RTI",6),(0x60,"RTS",6),(0x08,"PHP",3),(0x28,"PLP",4),(0x48,"PHA",3),
                 (0x68,"PLA",4),(0x88,"DEY",2),(0xA8,"TAY",2),(0xC8,"INY",2),(0xE8,"INX",2),(0x18,"CLC",2),(0x38,"SEC",2),
                 (0x58,"CLI",2),(0x78,"SEI",2),(0x98,"TYA",2),(0xB8,"CLV",2),(0xD8,"CLD",2),(0xF8,"SED",2)):
    setop(op, n, "IMP", c)
setop(0x20,"JSR","ABS",6)
